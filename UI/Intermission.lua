--[[--------------------------------------------------------------------------
    GideonRaid / UI / Intermission.lua

    RENDERING LAYER ONLY ("Intermission Coach"). This file may call the WoW API
    (frames, fonts, C_Timer, GetBindingKey). It contains NO business computation:
    everything comes from ns.Intermission (snapshot / setupView / run machine),
    from ns.Simulation (rehearsal view, ping help view) and from ns.Layout (the
    DISPOSITION of the panel: frame size, every offset, every label).

    THE DISPOSITION IS PURE (Core/Layout.lua). History: the fourth in-game test
    showed the big state ("2V2R") drawn ON TOP of the SIMULATION banner, because
    every element was placed with a FIXED Y offset. Here, no element carries a
    literal offset any more: UI.IntermissionRefresh() builds a spec (the current
    texts), Core measures and STACKS the blocks, and UI.ApplyLayout applies the
    result as-is. Two blocks can therefore never share a Y, in English as in
    French (tests/spec/layout_spec.lua locks it down for both languages).

    12.x prohibitions (see docs/CONVENTIONS.md):
      - no read of aura / health / resource (possible SECRET value);
      - no combat log event;
      - no addon -> addon message in an instance.

    PING: THE PLAYER PINGS, WITH THE NATIVE BLIZZARD PING KEYBIND. Measured in
    game by the raid lead: an addon CANNOT ping at all - neither from a macro nor
    from a binding ("action usable only by the Blizzard UI"). This file therefore
    READS the key the player bound (GetBindingKey, under pcall) only to DISPLAY
    it, and never pings, never prepares a macro.

    FLOW OF A RAID EVENING (only the ENCOUNTER_START arguments are read, and ALWAYS
    under pcall - see the boss filter block further down):
      a. before the pull, /gr -> "PLACE INTERMISSION PANEL": the frame is shown
         in placement mode and displays ONLY the Gideon illustration the raid
         lead delivered (no button, no text). It is dragged where the player
         wants it, the position is saved in the SavedVariables and `/gr inter ok`
         validates it;
      b. the player prepares the ping keybind and confirms with `/gr inter ok`
         -> panel closed;
      c. ENCOUNTER_START decides: IF the encounter is the configured target boss
         (allow-list of encounter ids, `/gr boss <id>`) OR the manual override is
         armed (/gr inter on), the pre-computed schedule is armed and the panel
         opens BY ITSELF shortly before each intermission. On any other boss
         NOTHING opens (safe default) and the chat says how to configure the right
         boss;
      d. the player clicks the composition they see (REDO corrects a mistake);
      e. at the end of the intermission the panel closes BY ITSELF;
      f. the next intermission follows the same cycle, automatically.
    THIS REAL FLOW IS UNCHANGED by the simulation mode below.

    WHICH BOSS: the allow-list of ENCOUNTER_START ids is the PRIMARY criterion (an
    integer, identical in every game language) and it is EMPTY by default, so the
    panel NEVER opens on its own until the raid lead names the right boss. The id
    of Entombed Sentinels is NOT known yet: `/gr idlog on` prints and memorizes
    what ENCOUNTER_START reports ("encounter seen: id=<id> name=<n> difficulty=<d>
    group=<g>"), and that line is what `/gr boss <id>` is given. The names are a
    SECONDARY criterion, language dependent, therefore empty by default too.

    THE PANEL IS THE RAID LEAD'S SURFACE, NOT A DOCUMENT (in-game report: "enleve
    tout le blabla"). It is read during a fight, so it carries NO sentence at all:
      - BEFORE a click: the THREE CARDS, stacked VERTICALLY, each one drawing the
        raid lead's own screenshot of the orbs (Texture/*.tga, a 256 px box,
        generated by tools/make_textures.py) inside a thin border. Nothing else -
        no title, no state line, no role line, no action line, no key reminder.
        The order is FROZEN by Core/Layout.INTERMISSION_CHOICE_ORDER (3V1R, 2V2R,
        1V3R from top to bottom) and a test locks it down;
      - AFTER a click: ONE WORD and nothing else - "Ping" (1V3R) and "Chasseur"
        (3V1R) in the theme GREEN, "BOSS" (2V2R) in the BIGGEST font of the
        window (44 px / 64 px, an EXPLICIT file and size from Core/Layout) - plus
        CORRECT, which brings the three pictures back. The colors come from
        Core/Layout.THEME (one constant, never a color written here);
      - IN PLACEMENT MODE: the illustration the raid lead delivered, and NOTHING
        else (no button, no label).
    The close cross ("X") is the ONLY way to close the panel: the former Close
    BUTTON was a sentence too many, and the cross was already there.
    WHERE A LEFTOVER TITLE COULD HIDE (raid-lead report: "there is still a title
    at the top of the intermission panel"): UI.ApplyLayout EMPTIES every element
    it is handed before showing the ones Core computed, this file creates NO
    title FontString any more (p.title is NOT set), Core/Layout.violations()
    REFUSES any text block a panel is not allowed to write
    (Layout.panelTextIds), and the strings that used to carry a title
    (ui.panelTitle, the placement blob of Intermission.setupView) are DELETED -
    a test asserts they can not come back.

    NO SOUND IS EVER PLAYED BY ITSELF (raid-lead decision): the three
    assignment soundboards (`Sound/assign-*.ogg`) play ONCE, on the Master
    channel, when the player CLICKS one of the three composition buttons - in the
    real flow as in a rehearsal - and NOTHING plays at any other moment: not when
    the panel opens (by itself or through `/gr sim inter`), not when it closes,
    not on a tick, not in a simulation that was not clicked. `Sound/
    intermission-start.ogg` STAYS packaged (the raid lead may want it back) and
    `/gr sound test start` plays it on REQUEST, but no automatic playback path
    exists any more - tests/spec/sound_spec.lua fails if one comes back.
    Core/Sound.lua owns the pure table state -> file and the one-playback-per-
    assignment gate; THIS file is the only one that calls PlaySoundFile, under
    pcall, so a missing file or a refused call leaves the addon silent without a
    Lua error and without blocking the rest of the rendering. CORRECT re-arms the
    gate (the next click plays the sound of the new composition) and so does
    every new intermission.

    THE PANEL ALWAYS DISAPPEARS WHEN THE INTERMISSION IS OVER. Two mechanisms,
    in this order:
      1. the intermission clock reaches DONE (Core/Intermission.tick) and this
         layer hides the panel - the normal path;
      2. the BOUNDED AUTO-CLOSE guard (Core/Intermission.newCloseGuard) is armed
         when the panel opens and RE-ARMED at every new intermission; its delay
         is configurable (Config.autoCloseSeconds, 30 s by default: the measured
         25 s window of a real intermission plus a 5 s margin) and can never be
         shorter than the real window, so it can only catch the cases where the
         normal close never happened (a clock that stopped ticking, a panel shown
         with no intermission running). A frame left on screen over the raid was
         reported in game: it is a bug, and this guard is the fix.

    CLOSE CROSS ("X", top right) on BOTH panels (the main one, UI/Panel.lua, and
    this one), and on the intermission panel it is THE way to close: during the
    placement it CANCELS the placement (same effect as the former Close button);
    during a REHEARSAL it CLOSES the rehearsal (the player is the one who closes
    it); during the real flow it only HIDES the panel: the intermission clock
    keeps running, the panel still closes by itself at the end and opens again at
    the next intermission (nothing is disarmed).

    SIMULATION MODE (two entries, reachable from the main panel AND from the
    chat): see the dedicated block below. It never arms, disarms or advances the
    ENCOUNTER_START timeline, never touches the live intermission state, never
    publishes a decision into the SavedVariables and never reads a combat event.
    Fourth in-game test: the rehearsal OPENS IMMEDIATELY and is closed by the
    player (no delay, no automatic close, one single cycle), and the ping entry
    is a plain HELP WINDOW (no guided sequence).
----------------------------------------------------------------------------]]
