--- Rebuilds the display from what Core/ computed AND applies the PURE layout.
--- The panel shows PICTURES and, once a composition is declared, ONE WORD: the
--- long explanations live in docs/, never on screen (raid-lead request: "enleve
--- tout le blabla").
--- ONCE A COMPOSITION IS CLICKED Core hides the three image buttons
--- (snapshot.showButtons = false) and shows CORRECT: the layout then simply does
--- not contain them, so the applier HIDES them (they can never be drawn on top
--- of the banner) and only the word stays.
--- UI APPLIES, CORE DECIDES: every block of the layout - its order, its size,
--- its texture, its label, the font of the word - is computed by
--- ns.Layout.intermissionPanel, and the COLOR of the word by ns.Layout.wordColor.
--- @return table the snapshot currently displayed
function UI.IntermissionRefresh()
    local p = ensurePanel()
    local c = config()
    local spec = {}

    if setupMode then
        -- PLACEMENT MODE (before the pull): the illustration the raid lead
        -- delivered (Core/Layout.placementPanel) and its small OK button UNDER it,
        -- and NOTHING ELSE. No composition, no label: the picture IS the reference
        -- of the size and the spot the window will occupy during the fight. The OK
        -- button saves the position and closes (UI.IntermissionConfirmSetup), the
        -- cross cancels, `/gr inter ok` does the same as the button, and the panel
        -- is dragged to the wanted spot like the combat panel.
        return UI.ApplyLayout(p, Layout.placementPanel(c.style), panelElements(p))
    end

    -- The ping policy is INJECTED into Core (Core never reads the SavedVariables)
    -- and decides the role order and the "PING: YES/NO" decision (still used by
    -- the chat commands, no longer displayed on the panel).
    -- During a rehearsal the panel shows the SIMULATION view: the live
    -- intermission (`state`) is left untouched (see displayedState()).
    local snap = Intermission.snapshot(displayedState(), c.pingMode, resolveBindingKey)
    if simRun ~= nil then
        -- Rehearsal: the SIMULATION banner (the ONE text the panel may show).
        snap = Simulation.forRehearsal(snap, simRun)
        spec.bannerLines = snap.simBannerLines
    end
    spec.showChoices = snap.showButtons
    spec.showRedo = snap.showRedo
    -- THE STYLE OF THE CARDS: the raid lead's choice (`/gr style`), the delivered
    -- one by default. It travels WITH the layout, so the combat panel's look is
    -- decided in ONE place (Core/Layout.BUTTON_STYLES) and this layer only applies
    -- the table it is handed.
    spec.style = c.style
    -- THE WORD: absent until a composition is declared, and always paired with
    -- the STATE it belongs to (never parsed back from the text).
    spec.wordText = snap.word
    spec.wordState = snap.wordKey

    local layout = Layout.intermissionPanel(spec)
    UI.ApplyLayout(p, layout, panelElements(p))
    -- THE FONT OF THE WORD comes from the layout block (Core decided the file and
    -- the size): the addon's own FontString, never an inherited Blizzard font
    -- object. Applied on every refresh, so a language or a state change can never
    -- leave a stale size behind.
    applyWordFonts(p, layout)
    -- THE COLOR OF THE WORD comes from THE THEME (Core): the two survival words
    -- are green, the big BOSS is gold. Both FontStrings take it (only one of them
    -- is part of the layout), so a language or a state change can never leave a
    -- stale color behind.
    if snap.wordKey ~= nil then
        local color = Layout.wordColor(snap.wordKey)
        p.word:SetTextColor(color.r, color.g, color.b)
        p.wordBig:SetTextColor(color.r, color.g, color.b)
    end
    return snap
end

--- Shows the COMBAT panel (automatic opening, manual toggle, rehearsal). The
--- BOUNDED AUTO-CLOSE guard is armed here, so the panel can never stay on screen
--- once the intermission is over, whatever path opened it (see the header):
---   - a rehearsal owns its own life: the PLAYER closes it (raid-lead decision),
---     so the guard is NOT armed for it;
---   - the placement mode is a configuration step, not a fight: no guard either.
function UI.IntermissionShow()
    local p = ensurePanel()
    setupMode = false
    UI.IntermissionApplyConfig()
    p:Show()
    UI.IntermissionRefresh()
    if simRun == nil then
        UI.ArmAutoClose()
    end
end

--- ARMS (or RE-ARMS) the bounded auto-close guard of the panel with the delay
--- Core/ computed: the configured safety delay, stretched to the whole real
--- window of the current intermission when that is longer (it can therefore never
--- cut a real intermission short). Called when the panel opens and at every new
--- intermission.
--- @return number delay seconds
function UI.ArmAutoClose()
    local c = config()
    local timeline = type(state) == "table" and state.timeline or nil
    local delay = Intermission.closeDelay(timeline, c.autoCloseSeconds)
    Intermission.armCloseGuard(closeGuard, delay)
    ensureTicker()
    return delay
end

--- Hides the panel. Nothing is left running: the auto-close guard is DISARMED
--- (the panel is gone; the next opening re-arms it) and a rehearsal is forgotten
--- (a rehearsal that is no longer on screen must not stay "running", otherwise
--- the next /gr sim inter would be refused).
function UI.IntermissionHide()
    local p = ensurePanel()
    setupMode = false
    p:Hide()
    Intermission.disarmCloseGuard(closeGuard)
    if simRun ~= nil then
        -- Hiding the panel ENDS a rehearsal: a rehearsal that is no longer on
        -- screen must not stay "running" (the next /gr sim inter would be refused
        -- and the player would be stuck with a hidden simulation).
        simRun = nil
        simState = nil
    end
end

--[[ SIMULATION MODE (rehearsal alone, with no boss and no raid) ----------------

     Two entries, reachable from the MAIN panel (two buttons) and from the chat
     (/gr sim inter | group | groupe, /gr sim ping, /gr sim stop):

       1. "INTERMISSION GROUP": the intermission panel opens RIGHT AWAY (fourth
          in-game test: the former 3 s delay is gone), the player clicks their
          composition, corrects it (CORRECT) and CLOSES THE PANEL THEMSELVES
          (close cross or Close button). ONE single cycle: nothing closes it
          automatically and nothing relaunches it. No boss, no raid, no
