--- Applies the EXPLICIT font Core declared for the word block of the layout: the
--- file and the size travel WITH the block, so the rendering layer writes neither
--- a file name nor a size (one single source, in Core/Layout.lua). Both
--- FontStrings can be refreshed by a single layout (only one of them is in it).
--- @param p Frame the intermission panel
--- @param layout table the layout just applied
local function applyWordFonts(p, layout)
    local targets = { word = p.word, wordBig = p.wordBig }
    for index = 1, #layout.blocks do
        local block = layout.blocks[index]
        local target = targets[block.id]
        if target ~= nil and type(block.fontFile) == "string" and type(block.fontSize) == "number" then
            if type(target.SetFont) == "function" then
                target:SetFont(block.fontFile, block.fontSize, "")
            end
        end
    end
end

