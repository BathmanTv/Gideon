--- Advances by one tick. dt is injected by the engine (local constant): Core
--- never reads the client clock.
---   0. the SIMULATIONS (intermission rehearsal, guided ping test): they own their
---      own run/state and never touch the two clocks below;
---   1. the encounter clock (ENCOUNTER_START is the origin, its arguments are
---      never read) opens the panel shortly before each pre-computed intermission;
---   2. the intermission clock counts the lead time, the visibility window, the
---      darkened room, then DONE -> the panel CLOSES BY ITSELF;
---   3. the BOUNDED AUTO-CLOSE guard: if the panel is STILL on screen once its
---      deadline has passed (a clock that never reached DONE, a panel opened with
---      no intermission running), it is hidden here. The panel can therefore never
---      stay over the raid after the intermission is over.
function UI.IntermissionTick(dt)
    -- The SIMULATION owns NO clock of its own any more: the panel opens right
    -- away and the player closes it (fourth in-game test), so nothing is ticked
    -- here. The clocks below are the REAL flow's, untouched by a rehearsal.
    if run ~= nil then
        local _, openedIndex = ns.Intermission.advanceRun(run, dt)
        if openedIndex ~= nil then
            -- A new intermission starts NOW: the panel opens (and, with it, the
            -- bounded auto-close guard is re-armed).
            beginIntermission(config())
        end
        if ns.Intermission.runFinished(run) then
            run = nil
        end
    end
    if state ~= nil then
        local phase = state.phase
        if phase == ns.Intermission.PHASE.PENDING or phase == ns.Intermission.PHASE.VISIBLE or phase == ns.Intermission.PHASE.DARK then
            ns.Intermission.tick(state, dt)
            if state.phase == ns.Intermission.PHASE.DONE then
                UI.IntermissionHide()
            end
        end
    end
    -- 3. THE SAFETY NET. Ticked even when no intermission is running (the guard
    -- is armed from the moment the panel opens), and it hides the panel exactly
    -- once: a frame left on screen over the raid was reported in game.
    if Intermission.tickCloseGuard(closeGuard, dt) then
        UI.IntermissionHide()
    end
    -- Rendering: only the intermission panel is redrawn (the ping help window is
    -- static: it shows the same text until it is closed).
    if panel ~= nil and panel:IsShown() then
        UI.IntermissionRefresh()
    end
    if not engineActive() then
        stopTicker()
    end
end

--- Player declaration: click on a COMPOSITION button (3V1R / 2V2R / 1V3R).
--- A bare ambiguous number ("1" or "3" alone) is refused by Core with a message
--- asking for the dominant color.
--- The ASSIGNMENT SOUNDBOARD of the declared state is played HERE, once, the
--- moment the declaration is accepted (real flow and rehearsal alike): nothing is
--- played without a declaration, and Core/Sound.lua refuses a second playback of
--- the same assignment (CORRECT re-arms it).
function UI.IntermissionDeclare(declaration)
    local c = config()
    if not c.enabled then
        UI.Print(Locale.t("ui.disabled"))
        return
    end
    -- SIMULATION: the click belongs to the REHEARSAL state, and NOTHING is
    -- published into the SavedVariables: the diagnostic kit must never read a
    -- rehearsal as a real decision.
    if simRun ~= nil then
        if simState == nil then
            UI.Print(Locale.t("sim.notOpen"))
            return
        end
        local _, simErr = ns.Intermission.declare(simState, declaration)
        if simErr ~= nil then
            UI.Print(Locale.format("ui.declarationRefused", tostring(simErr)))
            return
        end
        UI.PlayAssignSound(simState.declaration)
        UI.IntermissionRefresh()
        return
    end
    if state == nil or state.phase == ns.Intermission.PHASE.IDLE or state.phase == ns.Intermission.PHASE.DONE then
        -- Manual use outside a scheduled intermission (key, button, command).
        if not beginIntermission(c) then
            return
        end
    end
    local _, err = ns.Intermission.declare(state, declaration)
    if err ~= nil then
        UI.Print(Locale.format("ui.declarationRefused", tostring(err)))
        return
    end
    -- The soundboard of the state just declared, played ONCE (see Core/Sound.lua).
    UI.PlayAssignSound(state.declaration)
    -- We PUBLISH the timestamped decision into the SavedVariables: the
    -- diagnostic kit (GideonDiagAddon) reads it afterwards, with no chat input
    -- during combat and no inter-addon communication.
    local db = _G.GideonRaidDB
    if type(db) == "table" then
        local clock
        if type(date) == "function" then
            clock = date("%Y-%m-%d %H:%M:%S")
        end
        ns.Config.recordDecision(db, {
            composition = state.declaration,
            at = (type(time) == "function") and time() or nil,
            clock = clock,
            source = "coach-panel",
        })
    end
    UI.IntermissionRefresh()
end

--- REDO / CORRECT button: forgets the declaration and shows the three
--- composition choices again. Usable as many times as the player wants.
--- It also RE-ARMS the assignment soundboard: the next click plays the sound of
--- the composition it declares, even when it is the same one (documented).
function UI.IntermissionRedo()
    -- The state CURRENTLY shown: during a rehearsal it is the simulation state, so
    -- REDO corrects the simulated declaration and never the live one.
    local target = displayedState()
    if target == nil then
        return
    end
    local _, err = ns.Intermission.clearDeclaration(target)
    if err ~= nil then
        UI.Print(Locale.format("ui.redoFailed", tostring(err)))
        return
    end
    UI.ResetAssignSound()
    UI.IntermissionRefresh()
end

--[[ WHICH BOSS MAY OPEN THE PANEL (critical bug, fixed here) ------------------

     REPORTED BY THE RAID LEAD: "the window opens by itself during ANY boss fight!
     It must be limited to the boss we want."

     The panel used to be armed on EVERY `ENCOUNTER_START`. The decision is now a
     PURE FUNCTION of Core/BossFilter.lua:

       - the target is an ALLOW-LIST OF ENCOUNTER IDS (`ENCOUNTER_START` arg1: an
         INTEGER, the same on every client whatever the game language) plus an
         optional allow-list of NAMES (arg2, which the CLIENT translates: it stays
         EMPTY by default and is never guessed);
       - an EMPTY allow-list means NO AUTOMATIC OPENING (SAFE DEFAULT). A panel
         that does not open is better than a panel that opens on the wrong boss -
         and the chat says how to configure the right boss;
       - `/gr inter on` stays the MANUAL OVERRIDE: it arms the panel for the NEXT
         encounter whatever the boss, and it is CONSUMED at the end of it;
       - the arguments are read UNDER pcall (in 12.x an argument may be a SECRET
         value, and comparing one raises): an id that cannot be read is simply NOT
         a match, hence no opening - never a Lua error, never the wrong boss;
       - `/gr idlog on` is the MEASUREMENT mechanism: the real id of the target
         boss is read in game ("encounter seen: id=<id> ..."), never invented.

     Everything else of the flow is unchanged: the schedule arms on the pull, the
     panel opens `leadSeconds` before each intermission, closes at the end and
     opens again at the next one.
]]

--- The PURE decision of Core/BossFilter.lua, called UNDER pcall: the comparison
--- itself must be protected (a SECRET value raises on the smallest operation), and
--- ANY failure is a REFUSAL - never an automatic opening on an unknown boss.
--- @param encounter table|nil observation built by BossFilter.observeEncounter
--- @return table decision { shouldOpen, reason, id, name }
function UI.BossDecision(encounter)
    local ok, decision = pcall(BossFilter.evaluate, encounter, config())
    if not ok or type(decision) ~= "table" then
        return { shouldOpen = false, reason = BossFilter.REASON.UNREADABLE }
    end
    return decision
end

--- The chat line that says WHY nothing opens and WHAT to do about it: neither the
--- cleared target (a deliberate choice) nor a missing one must look like a bug. Pure
--- formatting, no state.
--- @param decision table|nil
--- @param resolved table|nil resolved configuration (to tell "cleared on purpose" from
---   "no target at all")
--- @return string message
function UI.BossRefusalMessage(decision, resolved)
    local reason = type(decision) == "table" and decision.reason or nil
    if reason == BossFilter.REASON.NO_TARGET then
        local c = type(resolved) == "table" and resolved or {}
        if c.bossTargetCleared == true then
            -- `/gr boss clear` was used: the short message names the command that
            -- brings the target back instead of repeating the whole procedure.
            return Locale.t("cmd.boss.clearedHint")
        end
        return Locale.t("cmd.boss.noTarget")
    end
    if reason == BossFilter.REASON.UNREADABLE then
        return Locale.t("cmd.boss.unreadable")
    end
    if type(decision) == "table" and decision.id ~= nil then
        return Locale.format("cmd.boss.notTarget", BossFilter.idText(decision.id))
    end
    return Locale.t("cmd.boss.notTargetNoId")
end

--- IDLOG (`/gr idlog on`): the measurement mechanism. Every `ENCOUNTER_START` is
--- printed - each value read under pcall, an unreadable value says so instead of
--- showing a fake number - and memorized NEWEST FIRST in the SavedVariables
--- (`GideonRaidDB.intermission.seenEncounters`, bounded), so the raid lead can
--- read the real id back after the pull. Nothing is sent anywhere, nothing is
--- invented: the id logged here IS the measured truth (the delivered default target
--- comes from exactly such a line), and any other boss is measured the same way.
--- @param encounter table|nil observation built by BossFilter.observeEncounter
--- @return boolean recorded
function UI.RecordSeenEncounter(encounter)
    UI.Print(BossFilter.seenLine(encounter))
    local db = _G.GideonRaidDB
    if type(db) ~= "table" then
        return false
    end
    local entry = BossFilter.toEntry(encounter)
    if type(time) == "function" then
        entry.at = time()
    end
    if type(date) == "function" then
        entry.clock = date("%Y-%m-%d %H:%M:%S")
    end
    ns.Config.recordSeen(db, entry)
    return true
end

--- Load-time warning (`PLAYER_LOGIN`): when NOTHING can open by itself, the player
--- MUST know it, otherwise the feature looks like a broken addon. Two different
--- situations, and only the FIRST one is worth a warning:
---   - no target at all (a build without any delivered default): warn;
---   - the target was cleared ON PURPOSE (`/gr boss clear`, `bossTargetCleared`): the
---     player knows what they did, and a warning at every login would read as if the
---     addon had forgotten something - stay silent.
--- Recomputed on every login: as soon as a target exists again, nothing is printed.
--- @return boolean printed
function UI.PrintBossFilterWarning()
    local c = config()
    if BossFilter.hasTarget(c) then
        return false
    end
    if c.bossTargetCleared == true then
        return false
    end
    UI.Print(Locale.t("cmd.boss.noTarget"))
    return true
end

--- ENCOUNTER_START is an instance event, not a combat log one. IT IS THE ONLY
--- place the auto-opening is decided: the schedule is armed ONLY when this
--- encounter is the configured target (or when the manual override is armed).
--- @param encounter table|nil observation built by Core/BossFilter.observeEncounter
function UI.IntermissionOnEncounterStart(encounter)
    -- A rehearsal must NEVER compete with a real fight: it is stopped the moment
    -- the encounter starts. This arms/disarms nothing by itself: the timeline
    -- below is armed exactly as before.
    if simRun ~= nil or (pingPanel ~= nil and pingPanel:IsShown()) then
        clearSimulation()
        UI.Print(Locale.t("sim.stoppedByEncounter"))
    end
    local c = config()

    -- IDLOG: measured BEFORE any decision, and even when the coach is disabled -
    -- the player asked for it explicitly and it is a measurement tool, not a
    -- decision. The id logged here is what `/gr boss <id>` will be given.
    if c.idlog then
        UI.RecordSeenEncounter(encounter)
    end

    if not c.enabled or not c.startOnEncounterStart then
        return
    end

    local decision = UI.BossDecision(encounter)
    if not decision.shouldOpen then
        -- NOTHING is armed for THIS encounter (the target boss is the ONLY one that
        -- may open the panel by itself, and the delivered default of the addon makes
        -- it work out of the box), and a schedule left over by a previous fight is
        -- disarmed too, so the panel can never open itself on the wrong boss. The
        -- refusal says WHICH case it is: cleared on purpose, no target at all, or
        -- simply another boss.
        run = nil
        if not engineActive() then
            stopTicker()
        end
        UI.Print(UI.BossRefusalMessage(decision, c))
        return
    end

    run = ns.Intermission.newRun(c.scheduleSeconds, c.leadSeconds)
    ensureTicker()
    if decision.reason == BossFilter.REASON.OVERRIDE then
        UI.Print(Locale.t("cmd.boss.overrideUsed"))
    end
    UI.Print(Locale.format("ui.armed", ns.Intermission.runRemaining(run), c.leadSeconds))
end

function UI.IntermissionOnEncounterEnd()
    run = nil
    UI.IntermissionStop()
    -- The MANUAL OVERRIDE lasts ONE encounter: it is consumed here, so the next
    -- encounter falls back to the configured target only.
    local db = _G.GideonRaidDB
    if type(db) == "table" and type(db.intermission) == "table" and db.intermission.overrideEncounter == true then
        db.intermission.overrideEncounter = false
        UI.Print(Locale.t("cmd.boss.overrideConsumed"))
    end
end

function UI.IntermissionSetEnabled(enabled)
    local db = _G.GideonRaidDB
    if type(db) ~= "table" or type(db.intermission) ~= "table" then
        UI.Print(Locale.t("ui.noSavedVariables"))
        return
    end
    db.intermission.enabled = enabled and true or false
    -- `/gr inter on` IS THE MANUAL OVERRIDE (raid-lead decision): besides enabling
    -- the module it arms the auto-opening for the NEXT encounter, WHATEVER the
    -- boss, and that arm is consumed at the end of the encounter. Disabling clears
    -- it, so it can never fire later on.
    db.intermission.overrideEncounter = enabled and true or false
    UI.Print(Locale.t(enabled and "ui.enabled" or "ui.disabledState"))
    if enabled then
        UI.Print(Locale.t("cmd.boss.overrideArmed"))
    end
end

function UI.IntermissionStatus()
    local c = config()
    local snap = ns.Intermission.snapshot(displayedState(), c.pingMode, resolveBindingKey)
    UI.Print(
        Locale.format(
            "ui.statusLine",
            Locale.t(c.enabled and "ui.wordEnabled" or "ui.wordDisabled"),
            snap.phase,
            tostring(snap.declaration)
        )
    )
    UI.Print(Locale.format("ui.timelineLine", c.visibilitySeconds, c.durationSeconds, c.scale))
    UI.Print(Locale.format("ui.pingPolicyLine", c.pingMode, snap.policyLine))
    UI.Print(Locale.format("ui.scheduleLine", #c.scheduleSeconds, c.leadSeconds))
    UI.Print(Locale.format("ui.soundLine", Locale.t(c.soundEnabled and "ui.wordEnabled" or "ui.wordDisabled")))
    -- WHICH BOSS may open the panel by itself: the allow-list of encounter ids (and
    -- names) of the auto-open filter, plus the state of the idlog.
    UI.Print(Locale.format("ui.bossLine", BossFilter.targetSummary(c), Locale.t(c.idlog and "ui.wordEnabled" or "ui.wordDisabled")))
end

--- `/gr inter ping`: which ping to use and which key to press, plus the binding
--- names tried (that is exactly what the in-game confirmation has to check).
function UI.IntermissionPrintPing()
    local c = config()
    local snap = ns.Intermission.snapshot(displayedState(), c.pingMode, resolveBindingKey)
    if snap.declaration == nil then
        UI.Print(Locale.t("ui.noDeclaration"))
        return
    end
    if snap.pingHint == nil then
        UI.Print(Locale.format("err.pingNotAllowed", tostring(snap.roleName), tostring(c.pingMode)))
        return
    end
    UI.Print(snap.pingHint.line)
    UI.Print(Locale.format("ui.pingCandidates", table.concat(snap.pingHint.bindNames, ", ")))
end

--- Prints the plan prepared out of game into the chat (same source as the panel).
function UI.PrintPlan()
    local me = UnitName("player")
    local c = config()
    local assignment, err = ns.Config.getAssignment()
    if not assignment then
        UI.Print(Locale.format("status.noAssignment", tostring(err)))
        return
    end
    local plan, planErr = ns.Intermission.buildPlan(assignment, me, c.pingMode, resolveBindingKey)
    if not plan then
        UI.Print(Locale.format("ui.unreadablePlan", tostring(planErr)))
        return
    end
    for _, line in ipairs(plan.lines) do
        UI.Print(line)
    end
end

--- Re-applies every LANGUAGE-DEPENDENT label (panel chrome + composition
--- buttons). Called at initialization and after a language change (/gr lang):
--- the strings come from Core, so the UI only copies them.
function UI.IntermissionApplyStaticText()
    local p = ensurePanel()
    -- The close cross is NOT part of a layout (it is chrome shared by the two
    -- panels): its label is refreshed here.
    p.closeCross:SetText(Locale.t("ui.closeCross"))
    -- The ping help window is built lazily: only refresh it when it exists.
    if pingPanel ~= nil then
        pingPanel.closeCross:SetText(Locale.t("ui.closeCross"))
        if pingPanel:IsShown() then
            UI.PingHelpRefresh()
        end
    end
    -- Everything else (title, buttons, disposition) is rebuilt from Core by a
    -- plain refresh: the labels live in Core/Layout.lua, in both languages.
    UI.IntermissionRefresh()
end

function UI.IntermissionInitialize()
    ensurePanel()
    UI.IntermissionApplyConfig()
    UI.IntermissionApplyStaticText()
end
