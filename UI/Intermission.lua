--- Starts ONE intermission (SILENT: no sound is played by itself any more): state
--- machine in PENDING, then VISIBLE... Used by the schedule (step c) and by the
--- manual commands.
--- @param c table resolved configuration
--- @return boolean started
local function beginIntermission(c)
    if state == nil then
        state = ns.Intermission.newState()
    end
    local started, err = ns.Intermission.start(state, {
        leadSeconds = c.leadSeconds,
        visibilitySeconds = c.visibilitySeconds,
        durationSeconds = c.durationSeconds,
    })
    if not started then
        UI.Print(Locale.format("ui.intermissionError", tostring(err)))
        return false
    end
    -- NEW INTERMISSION: the assignment soundboard gate is re-armed, so the SAME
    -- composition declared at the next intermission plays its sound again.
    UI.ResetAssignSound()
    -- THE PANEL OPENS: `leadSeconds` before the intermission. NO SOUND here (the
    -- raid lead removed the automatic intermission-start playback): the panel
    -- opening arms the bounded auto-close guard, nothing else.
    ensureTicker()
    UI.IntermissionShow()
    return true
end

