--- API ref 12.x: https://warcraft.wiki.gg/wiki/Secret_Values
--- Constraint: this panel only displays strings written by the player (a click
--- on a composition) or prepared out of game (GIDEON SavedVariables). No unit
--- value is read, hence no comparison on a secret value.
local function config()
    local db = _G.GideonRaidDB
    return ns.Config.resolveIntermission(db and db.intermission)
end

--- Reads the key the PLAYER bound to one of the native ping keybinds
--- (Options > Keybindings > ping system) - API:
--- https://warcraft.wiki.gg/wiki/API_GetBindingKey
--- READ ONLY, under pcall, and it is the ONLY ping-related API this addon
--- touches: it never sends a ping (the ping API is restricted to Blizzard's UI).
--- The candidates come from Core (their exact names are still to be confirmed in
--- game); a wrong candidate or a missing API simply means "no key known", and the
--- panel then asks for a keybind instead of showing a shortcut that does not
--- exist.
--- @param bindNames table|nil candidate binding names, ordered
--- @return string|nil key ("Q", "ALT-F", ...)
local function resolveBindingKey(bindNames)
    if type(bindNames) ~= "table" then
        return nil
    end
    if type(_G.GetBindingKey) ~= "function" then
        return nil
    end
    for index = 1, #bindNames do
        local ok, key = pcall(_G.GetBindingKey, bindNames[index])
        if ok and type(key) == "string" and key ~= "" then
            return key
        end
    end
    return nil
end

--- ---------------------------------------------------------------------------
--- ASSIGNMENT SOUNDBOARDS: the ONLY audio call of the whole addon.
--- ---------------------------------------------------------------------------

--- Plays one sound file on the MASTER channel. The FILE and the CHANNEL are
--- decided by Core/Sound.lua; this layer only hands them to the client.
--- API ref 12.x: https://warcraft.wiki.gg/wiki/API_PlaySoundFile
--- Constraint: a file that does not exist, a path the client refuses or an API
--- that is not there must leave the addon SILENT, without an error and without
--- interrupting the rest of the rendering: hence the type() guard and the pcall,
--- exactly like the ping keybind read above (GetBindingKey).
--- @param path string|nil client path ("Interface\AddOns\GideonRaid\Sound\...")
--- @param channel string|nil sound channel ("Master")
--- @return boolean played
local function playSoundFile(path, channel)
    if type(path) ~= "string" or path == "" then
        return false
    end
    if type(_G.PlaySoundFile) ~= "function" then
        return false
    end
    local ok = pcall(_G.PlaySoundFile, path, channel)
    return ok == true
end

--- THE ASSIGNMENT SOUNDBOARD of the composition the player just declared (real
--- flow as in a rehearsal). Core decides: one file per canonical state, ONE
--- playback per assignment, and the player preference; an unknown declaration, a
--- disabled preference or an already sounded assignment simply stays silent.
--- @param declaration string|nil canonical state ("1V3R" | "2V2R" | "3V1R")
--- @return boolean played
function UI.PlayAssignSound(declaration)
    local c = config()
    local request = Sound.takeAssignSound(soundAssigner, declaration, c.soundEnabled)
    if request == nil then
        return false
    end
    return playSoundFile(request.path, request.channel)
end

--[[ NO AUTOMATIC SOUND, EVER (raid-lead decision, replacing the former behaviour)

     The INTERMISSION START SOUND (`Sound/intermission-start.ogg`) used to be
     fired here, once, the moment the panel opened. It is NOT any more: NOTHING
     plays by itself, and the ONLY trigger of any sound is a CLICK on one of the
     three composition buttons (see UI.IntermissionDeclare -> UI.PlayAssignSound).

     What is left:
       - the file stays PACKAGED (Sound/ + GideonRaid.toc) and Core/Sound.lua
         keeps the pure gate (Sound.newStartGate / Sound.takeIntermissionStart):
         the raid lead can get the automatic playback back with a handful of
         lines, and the gate is still covered by tests/spec/sound_spec.lua;
       - `/gr sound test start` (UI.SoundTestStart below) still plays it ON
         REQUEST, so the file can be checked in game without waiting for a pull.

     THIS layer therefore calls no start sound at any point: opening the panel
     (automatic or `/gr sim inter`), closing it, a tick or a re-render are all
     SILENT. tests/spec/sound_spec.lua guards that silence: it fails as soon as
     an automatic playback path comes back.
]]

--- Remembers the current assignment (CORRECT, `/gr inter stop`, every new
--- intermission and every rehearsal): the NEXT click plays the sound of the
--- composition it declares - the natural behaviour after a correction.
function UI.ResetAssignSound()
    Sound.resetAssigner(soundAssigner)
    return soundAssigner
end

--- `/gr sound test start`: plays the INTERMISSION START sound on request, so the
--- raid lead can check it WITHOUT waiting for a pull. The player preference is
--- honoured, exactly like the three assignment soundboards: a muted sound stays
--- silent and says so, so a test can never contradict the setting.
--- @return boolean played
function UI.SoundTestStart()
    local c = config()
    if not c.soundEnabled then
        UI.Print(Locale.t("cmd.sound.testDisabled"))
        return false
    end
    local played = playSoundFile(Sound.startPath(), Sound.CHANNEL)
    if not played then
        UI.Print(Locale.format("cmd.sound.failed", tostring(Sound.START_FILE)))
        return false
    end
    UI.Print(Locale.format("cmd.sound.testStart", tostring(Sound.START_FILE)))
    return true
end

--- `/gr sound test <1v3r|2v2r|3v1r|start>`: plays ONE sound on request, so the
--- raid lead can hear and identify the files WITHOUT waiting for a fight.
--- BOUNDED: an unknown value is REFUSED (nothing is played), and the player
--- preference is honoured - a muted sound stays silent and says so, so a test can
--- never contradict the setting.
--- @param raw string|nil state written by the player ("1v3r", "2V2R", "start")
--- @return boolean played
function UI.SoundTest(raw)
    local flat = type(raw) == "string" and raw:lower():gsub("%s+", "") or ""
    if flat == "start" or flat == "intermission-start" then
        return UI.SoundTestStart()
    end
    local resolved = Sound.resolveState(raw)
    if resolved == nil then
        UI.Print(Locale.format("cmd.sound.unknownState", tostring(raw)))
        return false
    end
    local c = config()
    if not c.soundEnabled then
        UI.Print(Locale.t("cmd.sound.testDisabled"))
        return false
    end
    local played = playSoundFile(Sound.pathFor(resolved), Sound.CHANNEL)
    if not played then
        UI.Print(Locale.format("cmd.sound.failed", tostring(Sound.fileName(resolved))))
        return false
    end
    UI.Print(Locale.format("cmd.sound.test", resolved, tostring(Sound.fileName(resolved))))
    return true
end

--- The engine ticks only while something is timed: a SIMULATION (rehearsal or
--- ping test), the encounter clock (waiting for the next intermission), the
--- intermission itself, or the BOUNDED AUTO-CLOSE guard (armed from the moment
--- the panel opens: without it the guard would never fire on a panel opened with
--- no intermission running, which is exactly the frame left on screen).
local function engineActive()
    if simRun ~= nil then
        return true
    end
    if run ~= nil then
        return true
    end
    if Intermission.closeGuardArmed(closeGuard) then
        return true
    end
    local phase = state ~= nil and state.phase or nil
    return phase == ns.Intermission.PHASE.PENDING or phase == ns.Intermission.PHASE.VISIBLE or phase == ns.Intermission.PHASE.DARK
end

--- The state the panel is CURRENTLY showing. During a rehearsal the panel shows
--- the SIMULATION state: the live intermission (`state`) is never read nor
--- modified by a simulation.
local function displayedState()
    if simRun ~= nil then
        return simState
    end
    return state
end

local function stopTicker()
    if ticker then
        ticker:Cancel()
        ticker = nil
    end
end

local function ensureTicker()
    if ticker then
        return ticker
    end
    ticker = C_Timer.NewTicker(TICK_SECONDS, function()
        UI.IntermissionTick(TICK_SECONDS)
    end)
    return ticker
end

--- Reads one color of THE THEME (Core/Layout.THEME) as the three RGB floats the
--- client expects. The rendering layer writes NO color of its own: a green
--- scattered in this file is exactly how a green drifts away from the theme
--- between two releases. An unknown name falls back to the theme green, never to
--- a nil the client would refuse.
--- DECLARED HERE, before every frame builder: a Lua local is only visible to the
--- functions defined AFTER it.
--- @param name string theme key ("GREEN" | "BOSS" | "SIMULATION")
--- @return number r, number g, number b
local function themeColor(name)
    local entry = Layout.THEME[name] or Layout.THEME.GREEN
    return entry.r, entry.g, entry.b
end

local function ensurePanel()
    if panel then
        return panel
    end

    local p = CreateFrame("Frame", "GideonRaidIntermissionPanel", UIParent, "BackdropTemplate")
    p:SetSize(560, 360)
    p:SetMovable(true)
    p:EnableMouse(true)
    p:RegisterForDrag("LeftButton")
    p:SetClampedToScreen(true)
    p:SetScript("OnDragStart", function(self)
        self:StartMoving()
    end)
    p:SetScript("OnDragStop", function(self)
        self:StopMovingOrSizing()
        UI.IntermissionSavePosition()
    end)
    p:SetBackdrop({
        bgFile = "Interface\\DialogFrame\\UI-DialogBox-Background",
        edgeFile = "Interface\\DialogFrame\\UI-DialogBox-Border",
        tile = true,
        tileSize = 32,
        edgeSize = 32,
        insets = { left = 8, right = 8, top = 8, bottom = 8 },
    })

    -- NO fixed offset anywhere: the size, the position and the label of every
    -- element below come from Core/Layout.intermissionPanel(), applied as-is by
    -- UI.ApplyLayout. See the header: the "big state on top of the banner" bug
    -- came from literal Y offsets.
    --
    -- THERE IS NO TITLE, NO STATE LINE, NO ROLE LINE, NO ACTION LINE AND NO KEY
    -- REMINDER ANY MORE: the raid lead had them removed ("enleve tout le
    -- blabla"), and the layout no longer contains such a block, so there is no
    -- frame left for them either.

    -- CLOSE CROSS ("X", top right). Label and tooltip come from Core/Locale.lua
    -- (ui.closeCross / ui.closeTooltip), shared with the main panel. It is THE
    -- way to close the panel (the former Close BUTTON is gone).
    p.closeCross = UI.AttachCloseCross(p, function()
        UI.IntermissionCloseCross()
    end)

    -- The SIMULATION banner: displayed ONLY while a rehearsal drives the panel.
    -- The ONE text left, and only there: during the real flow the panel shows
    -- pictures and nothing else.
    p.simBanner = p:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
    p.simBanner:SetJustifyH("CENTER")
    p.simBanner:SetText("")
    p.simBanner:SetTextColor(themeColor("SIMULATION"))
    p.simBanner:Hide()

    -- THE ONE WORD written after a click ("Ping" / "BOSS" / "Chasseur"). TWO
    -- FontStrings, because a FontString carries ONE font: "wordBig" is the middle
    -- composition - the biggest element of the WINDOW, as the raid lead asked -
    -- and "word" carries the two others. Core/Layout.wordBlockId() decides which
    -- one the layout contains; the color comes from Core/Layout.THEME.
    -- THE FONT IS EXPLICIT: the addon creates its own FontString and calls
    -- SetFont(file, size, "") with the file and the sizes of Core/Layout (44 px
    -- and 64 px). A Blizzard font OBJECT would hide its real size - an addon
    -- cannot read it out of game - so "the biggest element of the window" would
    -- be a promise nobody could verify.
    p.word = p:CreateFontString(nil, "OVERLAY")
    p.word:SetFont(Layout.WORD_FONT_FILE, Layout.WORD_SIZE, "")
    p.word:SetJustifyH("CENTER")
    p.word:SetText("")
    p.word:Hide()

    p.wordBig = p:CreateFontString(nil, "OVERLAY")
    p.wordBig:SetFont(Layout.WORD_FONT_FILE, Layout.WORD_SIZE_BIG, "")
    p.wordBig:SetJustifyH("CENTER")
    p.wordBig:SetText("")
    p.wordBig:Hide()

    p.buttons = {}
    -- THE THREE CARDS: the player clicks the PICTURE of the composition they see
    -- above their head. The order (top to bottom) is FROZEN by Core
    -- (Layout.INTERMISSION_CHOICE_ORDER: 3V1R, 2V2R, 1V3R) and the picture itself
    -- is the texture of the state (Core/Textures.pathFor, applied by the layout):
    -- this layer writes no label at all.
    -- A CARD, not a Blizzard button: a thin border and a discreet dark background
    -- around the picture (Core/Layout.BUTTON_STYLES through UI.CreateCard), no
    -- chrome, no text, and ONE single feedback - the border lights up under the
    -- mouse (UI.CardBorder). Which style is used is Core's choice, never ours.
    -- ONCE THE CHOICE IS CLICKED the three pictures DISAPPEAR (Core decides:
    -- snapshot.showButtons): the layout no longer contains them, so they are
    -- HIDDEN and can never be drawn on top of the SIMULATION banner. CORRECT
    -- brings the three choices back.
    for index = 1, #ns.Layout.INTERMISSION_CHOICE_ORDER do
        local key = ns.Layout.INTERMISSION_CHOICE_ORDER[index]
        local button = UI.CreateCard("Button", p, ns.Layout.CHOICE_STYLE)
        button.state = key
        button:RegisterForClicks("LeftButtonUp")
        button:SetScript("OnEnter", function(self)
            UI.CardBorder(self, UI.CARD_STATE.HOVER)
        end)
        button:SetScript("OnLeave", function(self)
            UI.CardBorder(self, UI.CARD_STATE.REST)
        end)
        button:SetScript("OnMouseDown", function(self)
            UI.CardBorder(self, UI.CARD_STATE.PRESSED)
        end)
        button:SetScript("OnMouseUp", function(self)
            UI.CardBorder(self, UI.CARD_STATE.HOVER)
        end)
        button:SetScript("OnClick", function()
            UI.IntermissionDeclare(key)
        end)
        p.buttons[index] = button
    end

    -- THE PLACEMENT ILLUSTRATION (the drawing of the WINDOW itself). A plain card
    -- (no Button: there is nothing to click on the picture) holding the picture
    -- the raid lead delivered. Core/Layout.placementPanel() sizes it and names its
    -- style; the panel is DRAGGABLE, the cross cancels and /gr inter ok validates.
    p.placement = UI.CreateCard("Frame", p, ns.Layout.CHOICE_STYLE)

    -- REDO / CORRECT: forgets the declaration and brings the three pictures back.
    -- Usable as many times as needed (the state machine stays untouched). It is
    -- the ONLY written button of the panel - and only AFTER a click: before the
    -- click the panel writes nothing at all.
    p.redo = CreateFrame("Button", nil, p, "UIPanelButtonTemplate")
    p.redo:SetScript("OnClick", function()
        UI.IntermissionRedo()
    end)
    p.redo:Hide()

    -- THE OK BUTTON OF THE PLACEMENT PANEL (raid-lead decision: "Remet oui ok").
    -- A small, discreet button UNDER the illustration: it saves the position and
    -- closes, exactly like `/gr inter ok` - which stays available as a backup. It
    -- is part of the PLACEMENT layout only (Core/Layout.placementPanel): during a
    -- fight the layout does not contain it, so the applier hides it, and it can
    -- never be drawn over the three composition cards.
    p.placementOk = CreateFrame("Button", nil, p, "UIPanelButtonTemplate")
    p.placementOk:SetScript("OnClick", function()
        UI.IntermissionConfirmSetup()
    end)
    p.placementOk:Hide()

    p:Hide()
    panel = p
    return panel
end

--- The elements of the intermission panel, by block id (Core/Layout.lua names
--- every block). The rendering layer only maps an id to its frame.
--- @return table array of { id = string, frame = Frame|FontString }
local function panelElements(p)
    return {
